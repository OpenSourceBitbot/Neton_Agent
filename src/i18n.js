// 轻量 i18n：模块级 store + useSyncExternalStore，localStorage 持久化
// 用法：const { t, lang, setLang } = useLang();  t("nav.chat")
import { useSyncExternalStore } from "react";

const KEY = "NETON.lang.v1";
const listeners = new Set();

let current = localStorage.getItem(KEY) || "zh";

export function setLang(lang) {
  current = lang === "en" ? "en" : "zh";
  localStorage.setItem(KEY, current);
  listeners.forEach((l) => l());
}

export function toggleLang() {
  setLang(current === "zh" ? "en" : "zh");
}

function subscribe(cb) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

export function t(key, params) {
  let str = dict[current]?.[key] ?? dict.zh[key] ?? key;
  if (params && typeof str === "string") {
    for (const k in params) {
      str = str.replace(new RegExp("\\{" + k + "\\}", "g"), params[k]);
    }
  }
  return str;
}

/** 语言 hook：返回 { lang, setLang, toggleLang, t }，切换时全应用重渲染 */
export function useLang() {
  useSyncExternalStore(subscribe, () => current);
  return { lang: current, setLang, toggleLang, t };
}

